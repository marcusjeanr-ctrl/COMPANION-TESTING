const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const {runtime,hud} = require('./test_panel_tracking.cjs');
const source=fs.readFileSync(require('node:path').join(__dirname,'../dist/frontend.js'),'utf8');
const c=vm.createContext({});vm.runInContext(source.slice(0,source.indexOf('export function setup')),c);
const r=runtime(),b=r.ctx;
const data=b.parseCompanion('<rpg_companion>'+JSON.stringify({quests:[{id:'q_greyrat_meet',name:'Meet the young adventurer',objective:'Arrange an introduction'}],objectives:[{text:'Speak to the sponsor',quest:'q_greyrat_meet'}]})+'</rpg_companion>');
const chat=[{id:'a',role:'assistant',content:hud(),metadata:{rpg_companion:{swipes:{0:data}}}}];
const quests=b.questDetailsLatest(chat),before=JSON.stringify(chat);
assert.equal(c.objectiveQuestLabel('q_greyrat_meet',quests),'Meet the young adventurer');
assert.equal(c.objectiveQuestLabel('Meet the young adventurer',quests),'Meet the young adventurer');
assert.equal(c.objectiveQuestLabel('unknown_quest',quests),'unknown_quest');
assert.equal(c.objectiveQuestLabel('Q_GREYRAT_MEET',quests),'Meet the young adventurer');
assert.equal(c.objectiveQuestLabel('q_greyrat_meet',[...quests,{questId:'q_greyrat_meet',name:'Another assignment'}]),'q_greyrat_meet');
assert.equal(c.objectiveQuestLabel('reference',null),'reference');
assert.equal(c.objectiveQuestLabel(null,quests),null);
assert.equal(JSON.stringify(chat),before);assert.equal(r.writes.length,0);
console.log('Objective labels: ID, name, unknown, case, ambiguity and immutable reports passed');
